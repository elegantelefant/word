// ABOUTME: Tests for the Teams app package: the manifest it carries and the zip Teams uploads.
// ABOUTME: Reads the real icons and unzips the real package; nothing is mocked.
// @vitest-environment node

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { inflateSync } from "node:zlib";
import { unzipSync, strFromU8 } from "fflate";
import { teamsManifest, teamsPackage } from "../scripts/teams-package.mjs";

const ORIGINS = { tabOrigin: "https://addin.example.test" };

/** Decodes an 8-bit RGB or RGBA PNG into RGBA pixels (enough for our two icons). */
function decodePng(bytes: Buffer): { width: number; height: number; colorType: number; pixels: number[][] } {
  const width = bytes.readUInt32BE(16);
  const height = bytes.readUInt32BE(20);
  const colorType = bytes[25]!;
  const channels = colorType === 6 ? 4 : 3;
  const idat: Buffer[] = [];
  for (let at = 8; at < bytes.length; ) {
    const length = bytes.readUInt32BE(at);
    if (bytes.toString("ascii", at + 4, at + 8) === "IDAT") idat.push(bytes.subarray(at + 8, at + 8 + length));
    at += length + 12;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const stride = width * channels;
  const rows: Uint8Array[] = [];
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)]!;
    const row = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const prev = rows[y - 1] ?? new Uint8Array(stride);
    const out = new Uint8Array(stride);
    for (let i = 0; i < stride; i++) {
      const a = i >= channels ? out[i - channels]! : 0;
      const b = prev[i]!;
      const c = i >= channels ? prev[i - channels]! : 0;
      const p = a + b - c;
      const paeth = Math.abs(p - a) <= Math.abs(p - b) && Math.abs(p - a) <= Math.abs(p - c) ? a : Math.abs(p - b) <= Math.abs(p - c) ? b : c;
      const predictor = [0, a, b, (a + b) >> 1, paeth][filter]!;
      out[i] = (row[i]! + predictor) & 0xff;
    }
    rows.push(out);
  }
  const pixels = rows.flatMap((row) =>
    Array.from({ length: width }, (_, x) => {
      const px = Array.from(row.subarray(x * channels, x * channels + channels));
      return channels === 4 ? px : [...px, 255];
    }),
  );
  return { width, height, colorType, pixels };
}

describe("teamsManifest", () => {
  const manifest = teamsManifest({ version: "1.2.3", ...ORIGINS });

  it("opens one personal tab on the task pane's own origin", () => {
    expect(manifest.staticTabs).toEqual([
      expect.objectContaining({ contentUrl: "https://addin.example.test/teams.html", scopes: ["personal"] }),
    ]);
  });

  it("lists the tab host and Elefant's sign-in host as valid domains so the sign-in popup can run on both", () => {
    expect(manifest.validDomains).toEqual(["addin.example.test", "elefant.legal"]);
  });

  it("describes what the store asks for: Microsoft Teams in full, AI output, the Gemini route, sign-up and support", () => {
    const full = manifest.description.full;
    expect([
      full.indexOf("Microsoft Teams") === full.indexOf("Teams") - "Microsoft ".length,
      /generated by AI/.test(full),
      /Google Gemini/.test(full),
      full.includes("https://elefant.legal/sign-up"),
      full.includes("https://elefant.legal/resources/support"),
      full.split(/\s+/).length <= 500,
    ]).toEqual([true, true, true, true, true, true]);
  });

  it("carries the version it is given", () => {
    expect(manifest.version).toBe("1.2.3");
  });

  it("uses manifest version 1.29, the newest generally available schema, and declares that schema", () => {
    expect([manifest.manifestVersion, manifest.$schema]).toEqual([
      "1.29",
      "https://developer.microsoft.com/json-schemas/teams/v1.29/MicrosoftTeams.schema.json",
    ]);
  });
});

describe("teamsPackage", () => {
  const files = unzipSync(teamsPackage({ version: "1.2.3", ...ORIGINS }));

  it("puts exactly the manifest and both icons at the zip root", () => {
    expect(Object.keys(files).sort()).toEqual(["color.png", "manifest.json", "outline.png"]);
  });

  it("zips the same manifest teamsManifest builds", () => {
    expect(JSON.parse(strFromU8(files["manifest.json"]!))).toEqual(
      teamsManifest({ version: "1.2.3", ...ORIGINS }),
    );
  });
});

// Microsoft: colour icon 192x192 "on a solid or fully transparent square background"; outline 32x32
// "white with a transparent background" and no "extra padding around the symbol".
// https://learn.microsoft.com/en-us/microsoftteams/platform/concepts/deploy-and-publish/appsource/prepare/teams-store-validation-guidelines
describe("Teams icons", () => {
  const color = decodePng(readFileSync("teams/color.png"));
  const outline = decodePng(readFileSync("teams/outline.png"));

  it("has a 192 x 192 colour icon", () => {
    expect([color.width, color.height]).toEqual([192, 192]);
  });

  it("draws the colour icon on a solid, opaque square background", () => {
    const corners = [0, 191, 191 * 192, 192 * 192 - 1].map((i) => color.pixels[i]);
    expect(new Set(corners.map((px) => px!.join()))).toEqual(new Set([color.pixels[0]!.join()]));
    expect(color.pixels[0]![3]).toBe(255);
  });

  it("has a 32 x 32 outline icon", () => {
    expect([outline.width, outline.height]).toEqual([32, 32]);
  });

  it("draws the outline only in white on transparency", () => {
    const drawn = outline.pixels.filter((px) => px[3]! > 0);
    expect(drawn.length).toBeGreaterThan(0);
    expect(new Set(drawn.map((px) => px.slice(0, 3).join()))).toEqual(new Set(["255,255,255"]));
  });

  it("lets the outline symbol reach the icon's edges, without extra padding", () => {
    const columns = outline.pixels.map((px, i) => (px[3]! > 0 ? i % 32 : -1)).filter((x) => x >= 0);
    expect([Math.min(...columns), Math.max(...columns)]).toEqual([0, 31]);
  });

  it("uses the colour icon's background as the manifest accent colour", () => {
    const hex = `#${color.pixels[0]!.slice(0, 3).map((v) => v.toString(16).padStart(2, "0")).join("")}`.toUpperCase();
    expect(teamsManifest({ version: "1.0.0", ...ORIGINS }).accentColor).toBe(hex);
  });
});
